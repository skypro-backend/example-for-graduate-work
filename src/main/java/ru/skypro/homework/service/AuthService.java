package ru.skypro.homework.service;

import ru.skypro.homework.dto.Register;

/**
 * Сервис аутентификации и регистрации пользователей.
 * <p>
 * Определяет контракт для:
 * <ul>
 *   <li>Проверки учётных данных при входе в систему</li>
 *   <li>Регистрации новых пользователей с проверкой уникальности email и телефона</li>
 *   <li>Проверки занятости номера телефона</li>
 * </ul>
 * Все операции связаны с безопасностью и управлением учётными записями.
 * Реализация использует хеширование паролей через {@link org.springframework.security.crypto.password.PasswordEncoder}.
 *
 * @see AuthServiceImpl — основная реализация интерфейса
 * @see AuthController — использует этот сервис для обработки запросов /login и /register
 * @see Register — DTO для передачи данных при регистрации
 */
public interface AuthService {

    /**
     * Выполняет аутентификацию пользователя по логину (email) и паролю.
     * <p>
     * Проверяет существование пользователя и совпадение хешированного пароля.
     *
     * @param userName логин (email) пользователя
     * @param password пароль в открытом виде
     * @return {@code true}, если пользователь существует и пароль верен; иначе — {@code false}
     */
    boolean login(String userName, String password);

    /**
     * Регистрирует нового пользователя в системе.
     * <p>
     * Проверяет уникальность email и телефона. Если один из них уже используется — регистрация отклоняется.
     * При успешной регистрации пароль сохраняется в зашифрованном виде.
     *
     * @param register DTO с данными нового пользователя: email, пароль, имя, фамилия, телефон, роль
     * @return {@code true}, если регистрация прошла успешно; {@code false}, если email или телефон уже заняты
     */
    boolean register(Register register);

    /**
     * Проверяет, существует ли пользователь с указанным телефоном.
     * <p>
     * Используется при регистрации и обновлении профиля для обеспечения уникальности номера.
     *
     * @param phone телефон в формате строки (например, "+79991234567")
     * @return {@code true}, если пользователь с таким телефоном уже есть; иначе — {@code false}
     */
    boolean isPhoneExists(String phone);
}