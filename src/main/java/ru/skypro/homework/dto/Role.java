package ru.skypro.homework.dto;

/**
 * Перечисление ролей пользователей в системе.
 * Определяет уровень доступа пользователя к функциональности приложения.
 */
public enum Role {
    /**
     * Обычный пользователь.
     * Может создавать объявления, оставлять комментарии,
     * управлять своими объявлениями и комментариями.
     */
    USER,

    /**
     * Администратор.
     * Имеет полный доступ ко всем объявлениям и комментариям,
     * может управлять любыми ресурсами в системе.
     */
    ADMIN
}