package ru.skypro.homework.dto;

/**
 * Enum для ролей пользователей.
 * Определяет доступные роли в системе.
 * Основные функции:
 * - {@code USER} — обычный пользователь, может управлять своими объявлениями и комментариями;
 * - {@code ADMIN} — администратор, имеет полный доступ ко всем ресурсам.
 */
public enum Role {
    USER, ADMIN
}
