CREATE TABLE IF NOT EXISTS ads
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,
    price       INTEGER      NOT NULL,
    description TEXT,
    author_id   INTEGER      NOT NULL REFERENCES users (id),
    image       VARCHAR(255),
    created_at  BIGINT
);

