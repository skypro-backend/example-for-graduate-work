CREATE TABLE IF NOT EXISTS comments
(
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text      TEXT     NOT NULL,
    author_id INTEGER NOT NULL REFERENCES users (id),
    ad_id     INTEGER NOT NULL REFERENCES ads (id),
    created_at BIGINT
);
